ACK = r"""\section*{Acknowledgment}
%% IEEE Access requires AI-generated text to be disclosed here, with a citation to the AI system in the
%% sections that use it. Edit this paragraph so it says exactly how AI was used, or delete it if it was not.
The author used an AI assistant (Claude, Anthropic) to help draft and edit parts of the text and the
analysis code. The author checked every statement, number and reference and takes full responsibility
for the content.

"""

BIOS = r"""
\begin{IEEEbiography}[{\includegraphics[width=1in,height=1.25in,clip,keepaspectratio]{hani_abusharkh.jpg}}]{Hani AbuSharkh}
received the M.A.Sc. degree in information systems technology from Concordia University, Montreal, QC,
Canada, in 2011. He is currently pursuing the Ph.D. degree in informatics and computing at United Arab
Emirates University, Al Ain, United Arab Emirates. He is a Lecturer in Computer Science at the Higher
Colleges of Technology, United Arab Emirates. He previously
taught computer science for three years at Vanier College, Montreal, Canada. Before teaching, he worked for
more than ten years as a software engineer in the technology, automotive, aviation, defence and
secure-payments sectors, with organizations including Ford Motor Company, General Electric, Thales,
Lockheed Martin and Apple, on embedded and real-time systems, secure payment
technology and cybersecurity. He holds four Scrum certifications, CSM, A-CSM, CS-CSM and Scrum for AI.
His research interests include agile software development, mining software repositories and machine
learning for software project management.
\end{IEEEbiography}

\EOD

\end{document}
"""


def inline(path):
    return (PAPER / path).read_text().rstrip("\n")


def main():
    src = (PAPER / "main.tex").read_text()
    pre, rest = src.split(r"\begin{document}", 1)
    # number macros
    macros = inline("tables/numbers.tex") + "\n" + inline("tables/textnums.tex") + "\n"
    # body: from the abstract to the end of the bibliography
    body = rest[rest.index(r"\begin{abstract}"):rest.index(r"\end{thebibliography}") + len(r"\end{thebibliography}")]
    body = body.replace(r"\begin{IEEEkeywords}", r"\begin{keywords}").replace(r"\end{IEEEkeywords}", r"\end{keywords}")
    body = body.replace(r"\end{keywords}", r"\end{keywords}" + "\n\n\\titlepgskip=-21pt\n\n\\maketitle", 1)
    body = body.replace(r"\input{theory}", inline("theory.tex"))
    body = re.sub(r"\\tabinput\{([^}]*)\}", lambda m: inline(m.group(1)), body)
    body = body.replace(r"\begin{thebibliography}", ACK + r"\begin{thebibliography}", 1)
    assert r"\input{" not in body and r"\tabinput" not in body
    OUT.mkdir(exist_ok=True)
    out = OUT / "access_paper.tex"
    out.write_text(PREAMBLE + macros + "\n" + FRONT + body + "\n" + BIOS)
    print("wrote", out.relative_to(jr.ROOT), f"({len(out.read_text()):,} characters)")


if __name__ == "__main__":
    main()
