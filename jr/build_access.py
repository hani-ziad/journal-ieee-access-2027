"""Build the IEEE Access version of the paper: paper/ieee_access/access_paper.tex.

    python -m jr.build_access          (after python -m jr.build_paper)

It takes paper/main.tex (IEEEtran journal class) and rewrites it for the official IEEE Access template
(ieeeaccess.cls, LaTeX template of 13 May 2026): IEEE Access front matter, author block, acknowledgment
and biographies. Tables, the theory section and the number macros are inlined, so the result is one
self-contained file. Upload it to an Overleaf project made from the IEEE Access template together with
fig_carry.pdf, fig_primary.pdf, fig_reliability.pdf and the author photos.
"""
