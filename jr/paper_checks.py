"""Check every number typed into the running text of paper/main.tex against the result files.

    python -m jr.paper_checks        (set JR_TAWOS_DIR=data/raw/tawos_all for the paper's cohort)

Each check names the text as it appears in the paper, the value recomputed from the files, and
a tolerance. A check also fails if its text no longer appears in the paper, so edits to the
paper cannot silently drift from the checks. Table and theory numbers are generated by
jr/tables.py and need no check here; jr/theory_checks.py checks the theory identities.
"""
