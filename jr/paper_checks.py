GB = "Gradient boosting"
fails, n = [], 0


def check(text, actual, claimed, tol=0.0005):
    global n
    n += 1
    ok = abs(actual - claimed) <= tol and text in TEXT
    where = "" if text in TEXT else "  [text not found in paper]"
    print(("PASS " if ok else "FAIL ") + f"{text!r}: paper={claimed} computed={actual:.4f}{where}")
    if not ok:
        fails.append(text)


def pdiff(o, comp, prot="time", model=GB, col="delta"):
    return float(pdf[(pdf.outcome == o) & (pdf.comparison == comp) & (pdf.protocol == prot) & (pdf.model == model)][col].iloc[0])


def idiff(o, comp, cp, prot="time", col="delta"):
    return float(idf[(idf.outcome == o) & (idf.comparison == comp) & (idf.checkpoint == cp) & (idf.protocol == prot)
                     & (idf.model == GB)][col].iloc[0])


def pauc(o, fs, prot="time"):
    return float(pa[(pa.outcome == o) & (pa.features == fs) & (pa.protocol == prot) & (pa.model == GB)].auc.iloc[0])


def iauc(o, fs, cp):
    return float(ia[(ia.outcome == o) & (ia.features == fs) & (ia.checkpoint == cp) & (ia.protocol == "time")
                    & (ia.model == GB)].auc.iloc[0])


